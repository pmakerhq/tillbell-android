package com.pmaker.tillbell

import com.android.billingclient.api.BillingFlowParams.SubscriptionUpdateParams
import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable

// Messages of the Tillbell bridge contract, the specification of this library:
// https://github.com/pmakerhq/tillbell-rails/blob/main/docs/bridge-contract.md
//
// Replies are validated against the contract's JSON Schemas in the unit tests. Their schemas
// forbid unknown fields, so optional fields default to null and are left out when encoding;
// fields the schema requires (even when null, like basePlanId) have no default.

/** A plan shown by the paywall. A null [basePlanId] means the product's only base plan. */
@Serializable
internal data class Plan(
    val productId: String,
    val basePlanId: String? = null,
)

/** `products` request: the plans whose price the paywall shows. */
@Serializable
internal data class ProductsRequest(
    val products: List<Plan>,
)

/** Result of `products` and `restore`. */
@Serializable
internal enum class QueryResult {
    @SerialName("ok")
    OK,

    @SerialName("unavailable")
    UNAVAILABLE,

    @SerialName("error")
    ERROR,
}

/** A plan known to Google Play, with the price formatted for the customer's locale. */
@Serializable
internal data class PricedPlan(
    val productId: String,
    val basePlanId: String?,
    val formattedPrice: String,
)

/** `products` reply. [products] is set when [result] is OK, [message] may detail a failure. */
@Serializable
internal data class ProductsReply(
    val result: QueryResult,
    val products: List<PricedPlan>? = null,
    val message: String? = null,
)

/** Google Play replacement mode of a plan change, chosen by the server and passed through. */
@Serializable
internal enum class ReplacementMode(
    val playValue: Int,
) {
    WITH_TIME_PRORATION(SubscriptionUpdateParams.ReplacementMode.WITH_TIME_PRORATION),
    CHARGE_PRORATED_PRICE(SubscriptionUpdateParams.ReplacementMode.CHARGE_PRORATED_PRICE),
    WITHOUT_PRORATION(SubscriptionUpdateParams.ReplacementMode.WITHOUT_PRORATION),
    CHARGE_FULL_PRICE(SubscriptionUpdateParams.ReplacementMode.CHARGE_FULL_PRICE),
    DEFERRED(SubscriptionUpdateParams.ReplacementMode.DEFERRED),
}

/**
 * `purchase` request. [obfuscatedAccountId] is generated by the server and passed to Play
 * unchanged. [oldPurchaseToken] and [replacementMode] come together, for a plan change.
 */
@Serializable
internal data class PurchaseRequest(
    val productId: String,
    val basePlanId: String? = null,
    val obfuscatedAccountId: String,
    val oldPurchaseToken: String? = null,
    val replacementMode: ReplacementMode? = null,
)

/** Result of `purchase`. */
@Serializable
internal enum class PurchaseResult {
    @SerialName("purchased")
    PURCHASED,

    @SerialName("pending")
    PENDING,

    @SerialName("canceled")
    CANCELED,

    @SerialName("already_owned")
    ALREADY_OWNED,

    @SerialName("unavailable")
    UNAVAILABLE,

    @SerialName("error")
    ERROR,
}

/** `purchase` reply. [productId] and [purchaseToken] are set for PURCHASED and PENDING. */
@Serializable
internal data class PurchaseReply(
    val result: PurchaseResult,
    val productId: String? = null,
    val purchaseToken: String? = null,
    val message: String? = null,
)

/** A subscription purchase of the device's Google account. */
@Serializable
internal data class OwnedPurchase(
    val productId: String,
    val purchaseToken: String,
)

/** `restore` reply. [purchases] is set (possibly empty) when [result] is OK. */
@Serializable
internal data class RestoreReply(
    val result: QueryResult,
    val purchases: List<OwnedPurchase>? = null,
    val message: String? = null,
)

/** `manage` request: the subscription to manage, or null for all of them. It gets no reply. */
@Serializable
internal data class ManageRequest(
    val productId: String? = null,
)
